// controllers/chatbot.controller.js
const userModel = require("../models/user.model");
const codingModel = require("../models/coding.model");
const aptitudeModel = require("../models/aptitude.model");
const interviewModel = require("../models/interview.model");
const recommendationModel = require("../models/recommendation.model");
const chatModel = require("../models/chat.model");
const { getChatResponse } = require("../services/llm.service");
const { success, error } = require("../utils/response.util");

function toPercentage(part, total) {
  if (!total) return 0;
  return Math.round((Number(part) / Number(total)) * 100);
}

// Pulls together everything the LLM needs to know about this specific
// user, straight from MySQL. This is what makes the chatbot's replies
// personalized rather than generic.
async function buildUserContext(userId) {
  const user = await userModel.findById(userId);
  const skillLevelRow = await userModel.getSkillLevel(userId);

  const [codingSolved, codingTotal] = await Promise.all([
    codingModel.getSolvedCount(userId),
    codingModel.getTotalCount(),
  ]);
  const aptitudeOverall = await aptitudeModel.getOverallStats(userId);
  const technicalStats = await interviewModel.getCompletionStats(userId, "Technical");
  const hrStats = await interviewModel.getCompletionStats(userId, "HR");

  const recommendations = await recommendationModel.getRecommendations(userId);
  // Weak topics are the ones whose reason was generated by the
  // "below 50% accuracy" branch of the recommendation engine (Stage 6).
  const weakTopics = recommendations
    .filter((r) => r.reason.startsWith("You scored"))
    .map((r) => r.recommended_topic);

  return {
    userName: user.name,
    skillLevel: skillLevelRow ? skillLevelRow.skill_level : null,
    weakTopics,
    progress: {
      coding: toPercentage(codingSolved, codingTotal),
      aptitude: toPercentage(aptitudeOverall.correct || 0, aptitudeOverall.attempted || 0),
      technical: toPercentage(technicalStats.completed, technicalStats.total),
      hr: toPercentage(hrStats.completed, hrStats.total),
    },
  };
}

// POST /api/chat  (protected)  body: { message }
async function sendMessage(req, res, next) {
  try {
    const { message } = req.body;
    if (!message || typeof message !== "string" || !message.trim()) {
      return error(res, 400, "A non-empty message is required.");
    }

    const userContext = await buildUserContext(req.userId);
    const history = await chatModel.getRecentHistory(req.userId, 10);

    const reply = await getChatResponse(message.trim(), userContext, history);

    // Persist both sides of the conversation so history survives page reloads.
    await chatModel.saveMessage(req.userId, "user", message.trim());
    await chatModel.saveMessage(req.userId, "assistant", reply);

    return success(res, 200, "Message sent.", { reply });
  } catch (err) {
    next(err);
  }
}

// GET /api/chat/history  (protected)
async function getHistory(req, res, next) {
  try {
    const history = await chatModel.getFullHistory(req.userId);
    return success(res, 200, "Chat history fetched.", { history });
  } catch (err) {
    next(err);
  }
}

module.exports = { sendMessage, getHistory };
